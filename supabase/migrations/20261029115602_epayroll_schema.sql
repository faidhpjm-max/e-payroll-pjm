create function public.app_session_user(p_token text) returns text
language plpgsql security definer set search_path = public, pg_temp as $$
declare u text;
begin
  update sessions set expires_at = now() + interval '6 hours'
   where token = p_token and expires_at > now()
  returning username into u;
  if u is null then raise exception 'AUTH'; end if;
  return u;
end $$;

create function public.app_login(p_username text, p_password text) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare u users; t text;
begin
  select * into u from users where lower(username) = lower(trim(coalesce(p_username, '')));
  if not found or encode(sha256(convert_to(u.salt || coalesce(p_password, ''), 'UTF8')), 'hex') <> u.hash then
    perform pg_sleep(0.8);
    return jsonb_build_object('ok', false, 'error', 'Username atau password salah.');
  end if;
  delete from sessions where expires_at < now();
  t := replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
  insert into sessions values (t, u.username, now() + interval '6 hours');
  return jsonb_build_object('ok', true, 'data', jsonb_build_object('token', t, 'username', u.username, 'name', u.display_name));
end $$;

create function public.app_logout(p_token text) returns void
language sql security definer set search_path = public, pg_temp as $$
  delete from sessions where token = p_token;
$$;

create function public.app_change_password(p_token text, p_old text, p_new text) returns boolean
language plpgsql security definer set search_path = public, pg_temp as $$
declare uname text; u users; s text;
begin
  uname := app_session_user(p_token);
  if length(coalesce(p_new, '')) < 6 then raise exception 'Password baru minimal 6 karakter.'; end if;
  select * into u from users where lower(username) = lower(uname);
  if not found or encode(sha256(convert_to(u.salt || coalesce(p_old, ''), 'UTF8')), 'hex') <> u.hash then
    raise exception 'Password lama salah.';
  end if;
  s := gen_random_uuid()::text;
  update users set salt = s, hash = encode(sha256(convert_to(s || p_new, 'UTF8')), 'hex') where _row = u._row;
  return true;
end $$;

create function public.app_load(p_token text) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare uname text;
begin
  uname := app_session_user(p_token);
  return jsonb_build_object('username', uname, 'tables', jsonb_build_object(
    'Settings',  (select coalesce(jsonb_agg(to_jsonb(t) order by t._row), '[]'::jsonb) from settings t),
    'Employees', (select coalesce(jsonb_agg(to_jsonb(t) order by t._row), '[]'::jsonb) from employees t),
    'Payroll',   (select coalesce(jsonb_agg(to_jsonb(t) order by t._row), '[]'::jsonb) from payroll t),
    'Kasbon',    (select coalesce(jsonb_agg(to_jsonb(t) order by t._row), '[]'::jsonb) from kasbon t),
    'NaikGaji',  (select coalesce(jsonb_agg(to_jsonb(t) order by t._row), '[]'::jsonb) from naik_gaji t),
    'PHK',       (select coalesce(jsonb_agg(to_jsonb(t) order by t._row), '[]'::jsonb) from phk t)
  ));
end $$;

-- Terapkan daftar perubahan [{t, op: insert|update|delete, _row?, row?}] dalam satu transaksi.
create function public.app_apply(p_token text, p_ops jsonb) returns integer
language plpgsql security definer set search_path = public, pg_temp as $$
declare op jsonb; tbl text; cols text; n integer := 0;
begin
  perform app_session_user(p_token);
  perform pg_advisory_xact_lock(7301);
  for op in select value from jsonb_array_elements(p_ops) loop
    tbl := op->>'t';
    if tbl is null or tbl not in ('settings', 'employees', 'payroll', 'kasbon', 'naik_gaji', 'phk') then
      raise exception 'Tabel tidak dikenal: %', tbl;
    end if;
    if op->>'op' in ('insert', 'update') then
      select string_agg(quote_ident(k), ',') into cols from jsonb_object_keys(op->'row') k where k <> '_row';
    end if;
    if op->>'op' = 'insert' then
      execute format('insert into public.%I (%s) select %s from jsonb_populate_record(null::public.%I, $1)', tbl, cols, cols, tbl)
        using op->'row';
    elsif op->>'op' = 'update' then
      execute format('update public.%I set (%s) = (select %s from jsonb_populate_record(null::public.%I, $1)) where _row = $2', tbl, cols, cols, tbl)
        using op->'row', (op->>'_row')::bigint;
    elsif op->>'op' = 'delete' then
      execute format('delete from public.%I where _row = $1', tbl) using (op->>'_row')::bigint;
    else
      raise exception 'Operasi tidak dikenal: %', op->>'op';
    end if;
    n := n + 1;
  end loop;
  return n;
end $$;

revoke all on function public.app_session_user(text) from public, anon, authenticated;
revoke all on function public.app_login(text, text) from public;
revoke all on function public.app_logout(text) from public;
revoke all on function public.app_change_password(text, text, text) from public;
revoke all on function public.app_load(text) from public;
revoke all on function public.app_apply(text, jsonb) from public;
grant execute on function public.app_login(text, text) to anon, authenticated;
grant execute on function public.app_logout(text) to anon, authenticated;
grant execute on function public.app_change_password(text, text, text) to anon, authenticated;
grant execute on function public.app_load(text) to anon, authenticated;
grant execute on function public.app_apply(text, jsonb) to anon, authenticated;
