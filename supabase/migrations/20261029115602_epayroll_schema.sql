-- E-PAYROLL PJM: tabel pengganti sheet Google Sheets. `_row` menjaga urutan input (seperti nomor baris sheet).
create table public.settings (
  _row bigint generated by default as identity primary key,
  key text not null unique, value text, note text
);
create table public.users (
  _row bigint generated by default as identity primary key,
  username text not null unique, display_name text, hash text not null, salt text not null,
  created_at timestamp default (now() at time zone 'Asia/Jakarta')
);
create table public.employees (
  _row bigint generated by default as identity primary key,
  emp_id text not null unique, name text not null, email text, phone text, status text, dept text,
  position text, start_date date, job_site text, bank text, acc_no text, created_at timestamp, ptkp text
);
create table public.payroll (
  _row bigint generated by default as identity primary key,
  id text not null unique, period text not null, emp_id text not null, name text, bank text, acc_no text, job_site text,
  gp bigint, tl bigint, thr bigint, bruto bigint, kas_lalu bigint, pot_kas bigint, sisa_kas bigint,
  jht bigint, jp bigint, kes bigint, total_peng bigint, thp bigint, source text, created_at timestamp,
  status text, kes_base bigint, tax_base_ov bigint
);
create index payroll_period_idx on public.payroll (period);
create index payroll_emp_idx on public.payroll (emp_id);
create table public.kasbon (
  _row bigint generated by default as identity primary key,
  id text not null unique, emp_id text not null, name text, req_date date, amount bigint, status text,
  cair_date date, period text, note text, created_at timestamp
);
create table public.naik_gaji (
  _row bigint generated by default as identity primary key,
  id text not null unique, period text not null, emp_id text not null, name text,
  old_salary bigint, raise bigint, new_salary bigint, note text, created_at timestamp
);
create table public.phk (
  _row bigint generated by default as identity primary key,
  id text not null unique, period text, emp_id text not null, name text, phk_date date, reason text,
  rights text, amount bigint, note text, created_at timestamp
);
create table public.sessions (
  token text primary key, username text not null, expires_at timestamptz not null
);

-- Data hanya bisa diakses lewat fungsi app_* di bawah (RLS aktif, tanpa policy).
do $$ declare t text; begin
  foreach t in array array['settings','users','employees','payroll','kasbon','naik_gaji','phk','sessions'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;

